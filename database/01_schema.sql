-- ==============================================
-- 01_schema.sql
-- Creates the tables for the sample general
-- store database.
--
-- Run against the store_db database (NOT the
-- default "postgres" database). Type this as
-- ONE command on ONE line:
--   psql -U postgres -d store_db
--        -v ON_ERROR_STOP=1
--        -f database/01_schema.sql
--
-- SAFETY: This script is non-destructive. It
-- never drops or deletes anything. If any table
-- already exists, the script fails, and because
-- everything runs inside one transaction,
-- NOTHING is changed. To rebuild from scratch,
-- use the separate reset script on purpose.
-- ==============================================

BEGIN;

-- ----------------------------------------------
-- customers: people who have an account with
-- the store
-- ----------------------------------------------
CREATE TABLE customers (
    customer_id  INTEGER
                 GENERATED BY DEFAULT AS IDENTITY
                 PRIMARY KEY,
    full_name    TEXT NOT NULL,
    email        TEXT NOT NULL UNIQUE,
    city         TEXT NOT NULL,
    country      TEXT NOT NULL,
    signup_date  DATE NOT NULL
);

-- ----------------------------------------------
-- products: items the store sells
-- ----------------------------------------------
CREATE TABLE products (
    product_id    INTEGER
                  GENERATED BY DEFAULT AS IDENTITY
                  PRIMARY KEY,
    product_name  TEXT NOT NULL UNIQUE,
    category      TEXT NOT NULL,
    price         NUMERIC(10,2) NOT NULL
                  CHECK (price >= 0),
    stock_qty     INTEGER NOT NULL DEFAULT 0
                  CHECK (stock_qty >= 0)
);

-- ----------------------------------------------
-- orders: one row per checkout, placed by one
-- customer
-- ----------------------------------------------
CREATE TABLE orders (
    order_id     INTEGER
                 GENERATED BY DEFAULT AS IDENTITY
                 PRIMARY KEY,
    customer_id  INTEGER NOT NULL
                 REFERENCES customers (customer_id),
    order_date   DATE NOT NULL,
    status       TEXT NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending',
                                   'shipped',
                                   'delivered',
                                   'cancelled'))
);

-- ----------------------------------------------
-- order_items: the individual products inside
-- each order
-- ----------------------------------------------
CREATE TABLE order_items (
    order_item_id  INTEGER
                   GENERATED BY DEFAULT AS IDENTITY
                   PRIMARY KEY,
    order_id       INTEGER NOT NULL
                   REFERENCES orders (order_id),
    product_id     INTEGER NOT NULL
                   REFERENCES products (product_id),
    quantity       INTEGER NOT NULL
                   CHECK (quantity > 0),
    unit_price     NUMERIC(10,2) NOT NULL
                   CHECK (unit_price >= 0),
    UNIQUE (order_id, product_id)
);

-- ----------------------------------------------
-- Indexes: speed up lookups on foreign key
-- columns
-- ----------------------------------------------
CREATE INDEX idx_orders_customer_id
    ON orders (customer_id);
CREATE INDEX idx_order_items_product_id
    ON order_items (product_id);

-- ----------------------------------------------
-- Comments: human-readable descriptions stored
-- inside the database. Our app will later read
-- these and send them to the LLM as context.
-- ----------------------------------------------
COMMENT ON TABLE customers IS
    'People with an account at the store.';

COMMENT ON TABLE products IS
    'Items the store sells, with current '
    'price and stock.';

COMMENT ON TABLE orders IS
    'One row per checkout. Each order belongs '
    'to one customer.';

COMMENT ON TABLE order_items IS
    'Products within an order. '
    'Revenue = quantity * unit_price.';

COMMENT ON COLUMN products.price IS
    'Current list price. May differ from '
    'historical prices in order_items.';

COMMENT ON COLUMN orders.status IS
    'One of: pending, shipped, delivered, '
    'cancelled. '
    'Cancelled orders are not revenue.';

COMMENT ON COLUMN order_items.unit_price IS
    'Price actually paid per unit at the time '
    'of purchase.';

COMMIT;
